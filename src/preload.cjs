const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('whale', {
  getState: () => ipcRenderer.invoke('app:get-state'),
  saveConfig: (config, apiKey) => ipcRenderer.invoke('app:save-config', { config, apiKey }),
  chooseDirectory: (title) => ipcRenderer.invoke('dialog:directory', title),
  chooseArchive: () => ipcRenderer.invoke('dialog:archive'),
  prepareArchive: (target) => ipcRenderer.invoke('archive:prepare', target),
  chooseSkin: () => ipcRenderer.invoke('dialog:skin'),
  readSkin: (target) => ipcRenderer.invoke('skin:read', target),
  exportLocalSkin: (source, playerName) => ipcRenderer.invoke('skin:export-local', source, playerName),
  saveGeneratedSkin: (dataUrl) => ipcRenderer.invoke('skin:save-generated', dataUrl),
  scanSystem: () => ipcRenderer.invoke('system:scan'),
  listSystemVoices: () => ipcRenderer.invoke('voice:list'),
  previewSystemVoice: (name) => ipcRenderer.invoke('voice:preview', name),
  inspectInstance: (instancePath) => ipcRenderer.invoke('game:inspect', instancePath),
  workbuddyStatus: () => ipcRenderer.invoke('workbuddy:status'),
  workbuddyModels: () => ipcRenderer.invoke('workbuddy:models'),
  openWorkBuddy: () => ipcRenderer.invoke('workbuddy:open-app'),
  openBuildPlanner: () => ipcRenderer.invoke('build:open-window'),
  buildPlannerState: () => ipcRenderer.invoke('build:get-state'),
  setBuildPlannerMode: (mode) => ipcRenderer.invoke('build:set-mode', mode),
  sendBuildMessage: (message) => ipcRenderer.invoke('build:send', message),
  discussWithAgent: () => ipcRenderer.invoke('build:discuss-with-agent'),
  generateSurvivalBlueprint: () => ipcRenderer.invoke('build:survival-blueprint'),
  survivalStatus: () => ipcRenderer.invoke('build:survival-status'),
  startSurvivalBuild: (plan) => ipcRenderer.invoke('build:survival-start', plan),
  resumeSurvivalBuild: () => ipcRenderer.invoke('build:survival-resume'),
  stopSurvivalBuild: () => ipcRenderer.invoke('build:survival-stop'),
  clearBuildConversation: () => ipcRenderer.invoke('build:clear'),
  executeAdminBuild: () => ipcRenderer.invoke('build:admin-execute'),
  serverStatus: () => ipcRenderer.invoke('server:status'),
  setAdministrator: (name, enabled) => ipcRenderer.invoke('server:set-administrator', name, enabled),
  buildAndStartServer: (config) => ipcRenderer.invoke('server:build-start', config),
  stopServer: () => ipcRenderer.invoke('server:stop'),
  botStatus: () => ipcRenderer.invoke('bot:status'),
  startBot: (config) => ipcRenderer.invoke('bot:start', config),
  stopBot: () => ipcRenderer.invoke('bot:stop'),
  sakuraStatus: (network) => ipcRenderer.invoke('network:sakura-status', network),
  openSakura: () => ipcRenderer.invoke('network:sakura-open'),
  runSelfCheck: (config) => ipcRenderer.invoke('app:self-check', config),
  openPath: (target) => ipcRenderer.invoke('shell:open-path', target)
});
